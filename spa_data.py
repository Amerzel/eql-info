def _parse():
    out = {}
    for line in SPA_NAMES_RAW.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        sid, _, name = line.partition(" ")
        try:
            out[int(sid)] = name.strip()
        except ValueError:
            continue
    return out


SPA_NAMES = _parse()


def spa_name(effect_id: int) -> str:
    n = SPA_NAMES.get(effect_id)
    if n:
        return n
    return f"SE #{effect_id}"
